import io
import json
import sys

ROOT = r"C:\Users\Krilenxs\Desktop\fakao-pwa"
WRITE = "--write" in sys.argv
log = []


def load(name):
    with io.open(f"{ROOT}/questions/{name}.json", encoding="utf-8") as f:
        return json.load(f)


def save(name, data):
    if not WRITE:
        return
    with io.open(f"{ROOT}/questions/{name}.json", "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)


def find(data, qid):
    for q in data:
        if q.get("id") == qid:
            return q
    raise KeyError(qid)


def apply(name, qid, fields, label):
    """fields: dict of field -> (old, new) where old must match exactly."""
    data = load(name)
    q = find(data, qid)
    changed = []
    for field, (old, new) in fields.items():
        cur = q.get(field)
        if cur == new:
            log.append([qid, field, "SKIP(已是最新)"])
            continue
        if cur != old:
            raise SystemExit(f"[{qid}.{field}] 与预期不符:\n 期待: {old!r}\n 实际: {cur!r}")
        q[field] = new
        changed.append(field)
        log.append([qid, field, "改"])
    if changed:
        save(name, data)
    print(f"[{label}] {qid}: {changed or '无变化'}")


