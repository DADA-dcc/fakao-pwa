def apply(path, fixes):
    data = json.load(io.open(path, encoding='utf-8'))
    idx = {str(q.get('id')): q for q in data}
    changed = []
    for qid, patch in fixes.items():
        q = idx.get(qid)
        if not q:
            print('  未找到', qid)
            continue
        for k, v in patch.items():
            q[k] = v
        changed.append(qid)
    io.open(path, 'w', encoding='utf-8').write(json.dumps(data, ensure_ascii=False, indent=1))
    return changed


